/** Callback adaptable a react-i18next, sin acoplar el módulo de datos a React. */
export type ParashaTranslator = (key: string, defaultValue: string) => string;
export interface TranslatedParasha extends Parasha {
  jasidicLessons: ParashaLesson[];
}

/** Traduce los campos de la parashá seleccionada utilizando el i18n de la app.
 *  Las claves no definidas utilizan los textos originales en español.
 *  Ejemplos: parashot.bereshit.summary, parashot.bereshit.aliyot.1.description,
 *  parashot.bereshit.jasidicLessons.1.title.
 */
export function translateParasha(
  parasha: Parasha,
  translate: ParashaTranslator,
): TranslatedParasha {
  const tr = (key: string, fallback: string): string =>
    translate(`parashot.${parasha.id}.${key}`, fallback);
  return {
    ...parasha,
    name: tr('name', parasha.name),
    bookSpanish: tr('bookSpanish', parasha.bookSpanish),
    reference: tr('reference', parasha.reference),
    haftarah: tr('haftarah', parasha.haftarah),
    summary: tr('summary', parasha.summary),
    rashiInsight: tr('rashiInsight', parasha.rashiInsight),
    chabadInsight: tr('chabadInsight', parasha.chabadInsight),
    halachaFocus: tr('halachaFocus', parasha.halachaFocus),
    aliyot: parasha.aliyot.map(aliyah => ({
      ...aliyah,
      reference: tr(`aliyot.${aliyah.number}.reference`, aliyah.reference),
      description: tr(`aliyot.${aliyah.number}.description`, aliyah.description),
    })),
    jasidicLessons: (PARASHOT_LESSONS[parasha.id] ?? []).map((lesson, idx) => ({
      title: tr(`jasidicLessons.${idx + 1}.title`, lesson.title),
      snippet: tr(`jasidicLessons.${idx + 1}.snippet`, lesson.snippet),
    })),
  };
}
