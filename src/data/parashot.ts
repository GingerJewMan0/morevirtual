const normalizeName = (value: string): string => value
  .normalize('NFD')
  .replace(/[\u0300-\u036f]/g, '')
  .toLowerCase()
  .replace(/[^a-z0-9]/g, '');

// Una parashá simple se comprueba antes que las combinadas: "Lech-Lecha"
// contiene un guion, pero NO representa dos parashot.
export function matchHebcalParashot(title: string): string[] {
  const cleaned = title.replace(/^parash(?:at|a|á)\s+/i, '').trim();
  const direct = hebcalToId.get(normalizeName(cleaned));
  if (direct) return [direct];

  const pieces = cleaned.split(/\s*[-–—]\s*/).filter(Boolean);
  if (pieces.length === 2) {
    const first = hebcalToId.get(normalizeName(pieces[0]));
    const second = hebcalToId.get(normalizeName(pieces[1]));
    if (first && second && first !== second) return [first, second];
  }
  return [];
}

const localDate = (d: Date): string =>
  `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

/** Consulta el siguiente Shabat, en la diáspora por defecto (i=off).
 *  Si no hay lectura semanal (Yom Tov) o falla la red, devuelve null;
 *  no inventa una parashá ni devuelve Bereshit erróneamente.
 */
export async function fetchWeeklyParasha(
  today: Date = new Date(),
  israel = false,
): Promise<WeeklyParasha | null> {
  const shabbat = new Date(today.getFullYear(), today.getMonth(), today.getDate());
  shabbat.setDate(shabbat.getDate() + (6 - shabbat.getDay() + 7) % 7);
  const date = localDate(shabbat);
  const params = new URLSearchParams({
    v: '1', cfg: 'json', start: date, end: date,
    s: 'on', leyning: 'off', lg: 'en', i: israel ? 'on' : 'off',
  });

  try {
    const response = await fetch(`https://www.hebcal.com/hebcal?${params.toString()}`);
    if (!response.ok) throw new Error(`Hebcal HTTP ${response.status}`);
    const result: unknown = await response.json();
    if (!result || typeof result !== 'object' || !('items' in result)) return null;
    const items = (result as { items?: unknown }).items;
    if (!Array.isArray(items)) return null;
    const item = items.find((entry: unknown) =>
      entry !== null && typeof entry === 'object' &&
      (entry as { category?: unknown }).category === 'parashat' &&
      typeof (entry as { title?: unknown }).title === 'string',
    ) as { title: string } | undefined;
    if (!item) return null;
    const ids = matchHebcalParashot(item.title);
    return ids.length > 0 ? { ids, date, title: item.title } : null;
  } catch (error) {
    console.warn('No fue posible consultar la parashá semanal:', error);
    return null;
  }
}

/** Compatibilidad con las pantallas que ya importaban fetchCurrentParsha. */
export async function fetchCurrentParsha(): Promise<Parasha | null> {
  const weekly = await fetchWeeklyParasha();
  return weekly ? PARASHOT_DATA.find(p => p.id === weekly.ids[0]) ?? null : null;
}

